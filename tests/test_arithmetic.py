class SpanEndInvariantTest(unittest.TestCase):
    """The invariant the whole engine leans on: every from_jdn is constant on
    [j, span_end(j)) with span_end(j) > j. (Changing AT span_end is not
    required — leap's span end is the year boundary by design.)"""

    def _check(self, axes, lo, hi):
        for a in axes:
            j = lo
            while j < hi:
                e = a.span_end(j)
                self.assertGreater(e, j, (a, j))
                v = a.from_jdn(j)
                for k in range(j + 1, min(e, hi)):
                    self.assertEqual(a.from_jdn(k), v, (a, k))
                j = e

    def test_modern_window_all_axes(self):
        lo, hi = ar.civil2jdn(2019, 12, 25), ar.civil2jdn(2021, 1, 10)
        self._check(list(Axis), lo, hi)

    def test_far_future_jie_drift_seam(self):
        # from year 9233 節 terms land in the previous civil December; the
        # month pillar's span end must keep progressing across the seam
        lo, hi = ar.civil2jdn(9232, 12, 1), ar.civil2jdn(9233, 2, 1)
        self._check([Axis.cn_month_tiangan, Axis.cn_month_dizhi], lo, hi)


