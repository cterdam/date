class PillarTest(unittest.TestCase):
    def test_goldens(self):
        for y, m, d, tg, dz in _PILLAR_GOLDENS:
            j = ar.civil2jdn(y, m, d)
            self.assertEqual(ar.jdn2cn_day_tiangan(j), list(Tiangan)[tg], (y, m, d))
            self.assertEqual(ar.jdn2cn_day_dizhi(j), list(Dizhi)[dz], (y, m, d))

    def test_anchor(self):
        j = ar.civil2jdn(1949, 10, 1)
        self.assertEqual(ar.pillar_index_of(j), 0)
        self.assertEqual((j + ar.PILLAR_K) % 60, 0)

    def test_cycle_structure(self):
        j = ar.civil2jdn(2026, 7, 11)
        self.assertEqual(ar.jdn2cn_day_tiangan(j + 10), ar.jdn2cn_day_tiangan(j))  # stems: period 10
        self.assertEqual(ar.jdn2cn_day_dizhi(j + 12), ar.jdn2cn_day_dizhi(j))  # branches: period 12
        # the pair only repeats at 60
        pair = ar.jdn2cn_day_tiangan(j), ar.jdn2cn_day_dizhi(j)
        for k in range(1, 60):
            self.assertNotEqual((ar.jdn2cn_day_tiangan(j + k), ar.jdn2cn_day_dizhi(j + k)), pair, k)
        self.assertEqual((ar.jdn2cn_day_tiangan(j + 60), ar.jdn2cn_day_dizhi(j + 60)), pair)


