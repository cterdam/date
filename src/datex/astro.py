def _new_moon_series_jde(k: int) -> float:
    """JDE of lunation `k`'s new moon by the ch. 49 series alone."""
    t = k / 1236.85
    jde = (2451550.09766 + 29.530588861 * k
           + t * t * (0.00015437 + t * (-0.000000150 + 0.00000000073 * t)))
