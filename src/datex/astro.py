    m = (2.5534 + 29.10535670 * k - t * t * (0.0000014 + 0.00000011 * t)) * _RAD
    mp = (201.5643 + 385.81693528 * k
          + t * t * (0.0107582 + t * (0.00001238 - 0.000000058 * t))) * _RAD
    f = (160.7108 + 390.67050284 * k
         - t * t * (0.0016118 + t * (0.00000227 - 0.000000011 * t))) * _RAD
    om = (124.7746 - 1.56375588 * k + t * t * (0.0020672 + 0.00000215 * t)) * _RAD

