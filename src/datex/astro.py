def _series(terms, tau: float) -> float:
    return sum(a * math.cos(b + c * tau) for a, b, c in terms)


def solar_longitude_deg(jde: float) -> float:
    """Apparent geocentric solar longitude in degrees [0, 360)."""
    tau = (jde - 2451545.0) / 365250.0
    l = (_series(_L0, tau) + tau * (_series(_L1, tau) + tau * (
        _series(_L2, tau) + tau * (_series(_L3, tau) + tau * (
            _series(_L4, tau) + tau * _series(_L5, tau)))))) * 1e-8
    r = (_series(_R0, tau) + tau * (_series(_R1, tau)
                                    + tau * _series(_R2, tau))) * 1e-8
    lon = l / _RAD + 180.0 - 0.09033 / 3600.0  # geocentric, FK5 correction
    # nutation in longitude (truncated) and aberration
    t = tau * 10.0
    omega = (125.04452 - 1934.136261 * t) * _RAD
    l_sun = (280.4665 + 36000.7698 * t) * _RAD
    l_moon = (218.3165 + 481267.8813 * t) * _RAD
    dpsi = (-17.20 * math.sin(omega) - 1.32 * math.sin(2 * l_sun)
            - 0.23 * math.sin(2 * l_moon) + 0.21 * math.sin(2 * omega))
    lon += (dpsi - 20.4898 / r) / 3600.0
    return lon % 360.0


_SUN_DEG_PER_DAY = 360.0 / 365.2422


def solve_solar_longitude(target_deg: float, jde_near: float) -> float:
    """The JDE near `jde_near` at which the apparent solar longitude equals
    `target_deg` (secant-free Newton with the mean solar rate)."""
    jde = jde_near
    for _ in range(6):
        diff = (solar_longitude_deg(jde) - target_deg + 180.0) % 360.0 - 180.0
        jde -= diff / _SUN_DEG_PER_DAY
    return jde


