def lunar_longitude_deg(jde: float) -> float:
    """Apparent geocentric lunar longitude in degrees [0, 360)."""
    t = (jde - 2451545.0) / 36525.0
    lp = (218.3164477 + 481267.88123421 * t - 0.0015786 * t * t
          + t**3 / 538841.0 - t**4 / 65194000.0)
    d = (297.8501921 + 445267.1114034 * t - 0.0018819 * t * t
         + t**3 / 545868.0 - t**4 / 113065000.0) * _RAD
    m = (357.5291092 + 35999.0502909 * t - 0.0001536 * t * t
         + t**3 / 24490000.0) * _RAD
    mp = (134.9633964 + 477198.8675055 * t + 0.0087414 * t * t
          + t**3 / 69699.0 - t**4 / 14712000.0) * _RAD
    f = (93.2720950 + 483202.0175233 * t - 0.0036539 * t * t
         - t**3 / 3526000.0 + t**4 / 863310000.0) * _RAD
    e = 1 - 0.002516 * t - 0.0000074 * t * t
    e2 = e * e

    total = 0.0
    for td, tm, tmp, tf, coeff in _LUNAR_TERMS:
        amp = coeff * (e if abs(tm) == 1 else e2 if abs(tm) == 2 else 1.0)
        total += amp * math.sin(td * d + tm * m + tmp * mp + tf * f)
    a1 = (119.75 + 131.849 * t) * _RAD
    a2 = (53.09 + 479264.290 * t) * _RAD
    total += 3958 * math.sin(a1) + 1962 * math.sin(lp * _RAD - f) + 318 * math.sin(a2)

    omega = (125.04452 - 1934.136261 * t) * _RAD
    l_sun = (280.4665 + 36000.7698 * t) * _RAD
    l_moon = (218.3165 + 481267.8813 * t) * _RAD
    dpsi = (-17.20 * math.sin(omega) - 1.32 * math.sin(2 * l_sun)
            - 0.23 * math.sin(2 * l_moon) + 0.21 * math.sin(2 * omega))
    return (lp + total * 1e-6 + dpsi / 3600.0) % 360.0


_MOON_SUN_DEG_PER_DAY = 360.0 / 29.530588861


def new_moon_jde(k: int) -> float:
    """JDE of lunation `k`'s new moon (k = 0 is the first of 2000): the
    ch. 49 series instant refined by root-solving the actual conjunction
    (lunar longitude = solar longitude) in the full theories."""
    jde = _new_moon_series_jde(k)
    for _ in range(4):
        diff = (lunar_longitude_deg(jde) - solar_longitude_deg(jde)
                + 180.0) % 360.0 - 180.0
        jde -= diff / _MOON_SUN_DEG_PER_DAY
    return jde


