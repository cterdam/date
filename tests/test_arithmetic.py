"""Unit tests for date.arithmetic.

Oracles: the stdlib datetime module (proleptic Gregorian, ISO weeks) for a
broad sweep over years 1-9999, literature anchors for the JDN epoch, and
sxtwl-derived goldens for the sexagenary day pillar (see golden/gen_pillars.py).
"""

import datetime
import unittest

from datex import arithmetic as ar
from datex import Axis, Dizhi, Tiangan, Weekday, Zodiac

_RD_TO_JDN = 1_721_425  # date.toordinal() + this == JDN


class AnchorTest(unittest.TestCase):
    def test_epoch_anchors(self):
        self.assertEqual(ar.civil2jdn(2000, 1, 1), 2_451_545)  # J2000.0
        self.assertEqual(ar.civil2jdn(1970, 1, 1), 2_440_588)  # Unix epoch
        self.assertEqual(ar.civil2jdn(1, 1, 1), 1_721_426)  # RD 1
        # JDN 0 is -4713-11-24 proleptic Gregorian (Nov 24, 4714 BC)
        self.assertEqual(ar.jdn2civil(0), (-4713, 11, 24))

    def test_round_trip_across_eras(self):
        for j in range(-1_000_000, 6_000_000, 9_973):
            y, m, d = ar.jdn2civil(j)
            self.assertEqual(ar.civil2jdn(y, m, d), j)


class StdlibSweepTest(unittest.TestCase):
    def test_sweep_against_datetime(self):
        for ordinal in range(1, 3_652_059, 4_243):
            d = datetime.date.fromordinal(ordinal)
            j = ordinal + _RD_TO_JDN
            self.assertEqual(ar.jdn2civil(j), (d.year, d.month, d.day))
            self.assertEqual(ar.civil2jdn(d.year, d.month, d.day), j)
            self.assertEqual(int(ar.jdn2weekday(j)), d.isoweekday())
            self.assertEqual(ar.jdn2doy(j), d.timetuple().tm_yday)
            iso = d.isocalendar()
            self.assertEqual(ar.jdn2week(j), (iso[0], iso[1]))

    def test_iso_week_edges(self):
        cases = [
            ((2005, 1, 1), (2004, 53)),
            ((2005, 1, 2), (2004, 53)),
            ((2005, 12, 31), (2005, 52)),
            ((2007, 1, 1), (2007, 1)),
            ((2007, 12, 30), (2007, 52)),
            ((2007, 12, 31), (2008, 1)),
            ((2008, 12, 28), (2008, 52)),
            ((2008, 12, 29), (2009, 1)),
            ((2010, 1, 3), (2009, 53)),
        ]
        for (y, m, d), expected in cases:
            self.assertEqual(ar.jdn2week(ar.civil2jdn(y, m, d)), expected, (y, m, d))
            iso = datetime.date(y, m, d).isocalendar()
            self.assertEqual(expected, (iso[0], iso[1]))  # the case itself is sound

    def test_leap(self):
        self.assertTrue(ar.is_leap(2000))
        self.assertTrue(ar.is_leap(2024))
        self.assertTrue(ar.is_leap(-4712))
        self.assertFalse(ar.is_leap(1900))
        self.assertFalse(ar.is_leap(2026))
        self.assertFalse(ar.is_leap(-4700))


